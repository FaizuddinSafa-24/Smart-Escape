export const STRINGS = { en, bn };

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
export function localizeDigits(value, lang) {
  const s = String(value);
  return lang === 'bn' ? s.replace(/[0-9]/g, (d) => BN_DIGITS[d]) : s;
}

function fill(template, params, lang) {
  return template.replace(/\{(\w+)\}/g, (_, k) =>
    k in params ? (typeof params[k] === 'number' ? localizeDigits(params[k], lang) : String(params[k])) : `{${k}}`,
  );
}

export function makeT(lang) {
  const dict = STRINGS[lang] || en;
  const t = (key, params = {}) => fill(dict[key] ?? en[key] ?? key, params, lang);
  t.err = ({ key, params }) => fill(dict.errors[key] ?? en.errors[key] ?? key, params || {}, lang);
  t.num = (n) => localizeDigits(n, lang);
  return t;
}
